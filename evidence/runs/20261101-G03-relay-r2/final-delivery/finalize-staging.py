import hashlib,json,re
from pathlib import Path
root=Path(r'D:\ADMIN\Desktop\WEIJI\zonghe');stage=Path(__file__).parent;dest=stage/'final-delivery'
rp='evidence/runs/20261101-G03-relay-r2';run=root/rp
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
read=lambda p:json.loads(p.read_text(encoding='utf-8'))
changes=read(dest/'changes.json')
def write(rel,text):
    p=dest/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text,encoding='utf-8')
    row=dict(path=rel,before_sha256=sha(root/rel) if (root/rel).exists() else None,after_sha256=sha(p))
    changes[:]=[r for r in changes if r['path']!=rel];changes.append(row)
rel=rp+'/work-card.md'
write(rel,(dest/rel).read_text(encoding='utf-8').replace('../../../../','../../../'))
m=read(run/'manifest.json')
m.update(status='complete',verdict='pass',verdict_scope='single relay response and recovery only',evidence_scope=['static','build','simulation','bench'],actual_power_executed=True,actual_trigger_count=1,conditions='conditions-ready.json',report='first-experiment-report.md',trial_result='trial-result.json',physical_valid=0,formal_G03_verdict=None)
write(rp+'/manifest.json',json.dumps(m,ensure_ascii=False,indent=2))
# All production sources must still match the exact workspace used for the r2 build.
sources=[]
for p in sorted((root/'BMS_EXv1.1/BMS_EX').rglob('*')):
    if not p.is_file():continue
    if p.suffix.lower() not in ('.c','.h','.s','.sct','.uvprojx','.ioc'):continue
    rel=str(p.relative_to(root)).replace('\\','/')
    assert (stage/rel).is_file(),rel
    assert sha(p)==sha(stage/rel),'Production source changed: '+rel
    sources.append(dict(path=rel,sha256=sha(p)))
write(rp+'/production-source-manifest.json',json.dumps(dict(basis='Production .c/.h/.s/.sct/.uvprojx/.ioc comparison with the r2 build workspace; no production-source edits after verified flash',excluded_generated_output='Secure_nsclib/secure_nsclib.o is generated by --import_cmse_lib_out, not an input source; the existing root output is preserved',firmware=read(run/'artifact-manifest.json')['firmware'],files=sources),indent=2))
# Check newly authored Markdown links against staged files or retained evidence.
checked=0
for item in changes:
    if not item['path'].endswith('.md'):continue
    if not item['path'].startswith(rp+'/'):continue
    p=dest/item['path']
    for href in re.findall(r'\]\(([^)]+)\)',p.read_text(encoding='utf-8')):
        if href.startswith(('https:','http:','#')):continue
        relative=(Path(item['path']).parent/href).as_posix()
        assert (dest/relative).exists() or (root/relative).exists(),(item['path'],href)
        checked+=1
(dest/'changes.json').write_text(json.dumps(changes,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(dict(changes=len(changes),production_source_files=len(sources),production_sources_match=True,checked_markdown_links=checked)))
